DISPATCH_PRELUDE = """\
#include "dispatch.hpp"

#include <cstdio>
#include <cstring>

#include "ext_comm.hpp"
#include "ws_protocol.hpp"

using namespace ws_proto;

/* Static functions */

/* Copy a wire request into its typed struct, returns true on size mismatch */
template <typename Req>
static bool _parse(const std::vector<uint8_t>& msg, Req& req)
{
    if(msg.size() != sizeof(Req))
    {
        // Err: malformed request
        return true;
    }
    memcpy(&req, msg.data(), sizeof(Req));
    return false;
}

template <typename Resp>
static std::vector<uint8_t> _serialize(const Resp& resp)
{
    std::vector<uint8_t> out(sizeof(Resp));
    memcpy(out.data(), &resp, sizeof(Resp));
    return out;
}

static std::vector<uint8_t> _respBool(const header_t& h, bool isError)
{
    respBool_t resp = {};
    resp.h = h;
    resp.isError = isError ? 1 : 0;
    return _serialize(resp);
}

/* Dispatch one request to the ext communication layer */
std::vector<uint8_t> server_dispatch(const std::vector<uint8_t>& msg)
{
    if(msg.size() < sizeof(header_t))
    {
        // Err: too short to carry a header, no way to answer meaningfully
        return {};
    }

    header_t h = {};
    memcpy(&h, msg.data(), sizeof(header_t));

    switch(h.type)
    {
"""


def gen_dispatch():
    out = header("dispatch.cpp", [
        "ws_protocol request dispatcher — see dispatch.hpp.",
    ])
    out += "\n" + DISPATCH_PRELUDE

    cases = []
    for cmd in COMMANDS:
        rq = wire_req_name(cmd)
        b = f"        case {enum_name(cmd)}:\n        {{\n"
        b += f"            {rq} req = {{}};\n"
        b += "            if(_parse(msg, req)) return _respBool(h, true);\n\n"
        if cmd.log:
            b += f"            printf(\"[cds-server] {cmd.log}\\n\");\n"
        setup, call = _dispatch_call(cmd)
        b += setup
        if cmd.resp == "bool":
            b += f"            return _respBool(h, {call});\n"
        elif has_bool(cmd.resp):
            s = STRUCTS[cmd.resp]
            b += f"            {cmd.resp} ret = {call};\n\n"
            b += f"            {wire_resp_name(cmd)} resp = {{}};\n"
            b += "            resp.h = h;\n"
            for f in s.fields:
                if f.type == "bool":
                    b += f"            resp.{f.name} = ret.{f.name} ? 1 : 0;\n"
                else:
                    b += f"            resp.{f.name} = ret.{f.name};\n"
            b += "            return _serialize(resp);\n"
        else:
            b += f"            {wire_resp_name(cmd)} resp = {{}};\n"
            b += "            resp.h = h;\n"
            b += f"            resp.p = {call};\n"
            b += "            return _serialize(resp);\n"
        b += "        }\n"
        cases.append(b)
    out += "\n".join(cases)

    out += """
        default:
            // Err: unknown message type
            return _respBool(h, true);
    }
}
"""
    return out


def _dispatch_call(cmd):
    """Returns (setup lines, call expression) to invoke the ext function."""
    if cmd.req is None:
        return "", f"{cmd.cfn}()"
    if isinstance(cmd.req, tuple):
        _, _, n = cmd.req
        return "", f"{cmd.cfn}(req.{n})"
    if has_bool(cmd.req):
        setup = f"            {cmd.req} par = {{}};\n"
        for f in STRUCTS[cmd.req].fields:
            if f.type == "bool":
                setup += f"            par.{f.name} = req.{f.name} != 0;\n"
            else:
                setup += f"            par.{f.name} = req.{f.name};\n"
        setup += "\n"
        return setup, f"{cmd.cfn}(par)"
    return "", f"{cmd.cfn}(req.p)"


