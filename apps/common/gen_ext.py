BASE_SIZES = {"ext_coord_t": 4, "bool": 1, "uint8_t": 1}


def size_of(type_name):
    if type_name in BASE_SIZES:
        return BASE_SIZES[type_name]
    return sum(size_of(f.type) for f in STRUCTS[type_name].fields)


def has_bool(type_name):
    if type_name == "bool":
        return True
    if type_name in BASE_SIZES:
        return False
    return any(has_bool(f.type) for f in STRUCTS[type_name].fields)


def enum_name(cmd):
    """InitRocket -> WS_MSG_INIT_ROCKET"""
    out = ""
    for i, ch in enumerate(cmd.wire):
        if ch.isupper() and i > 0 and not cmd.wire[i - 1].isupper():
            out += "_"
        out += ch.upper()
    return "WS_MSG_" + out


def req_size(cmd):
    n = 1  # header_t
    if cmd.req is None:
        return n
    if isinstance(cmd.req, tuple):
        return n + size_of(cmd.req[1])
    return n + size_of(cmd.req)


def resp_size(cmd):
    if cmd.resp == "bool":
        return 2  # header_t + uint8_t
    n = 1
    for f in STRUCTS[cmd.resp].fields:
        n += 1 if f.type == "bool" else size_of(f.type)
    return n


def req_breakdown(cmd):
    if cmd.req is None:
        return ""
    if isinstance(cmd.req, tuple):
        return f" // 1 + {size_of(cmd.req[1]) // 4}f"
    if has_bool(cmd.req):
        return _field_breakdown(cmd.req)
    return f" // 1 + {size_of(cmd.req) // 4}f"


def resp_breakdown(cmd):
    if cmd.resp == "bool":
        return " // 1 + u8"
    return _field_breakdown(cmd.resp)


def _field_breakdown(struct_name):
    parts = []
    for f in STRUCTS[struct_name].fields:
        parts.append("u8" if f.type == "bool" else f"{size_of(f.type) // 4}f")
    return " // 1 + " + " + ".join(parts)


def _check_no_nested_bool(struct_name):
    """bool is converted to uint8_t on the wire, but only at the top level of
    request/response structs: a bool buried in a nested struct would cross
    the wire raw. Fail generation loudly instead."""
    for f in STRUCTS[struct_name].fields:
        if f.type not in BASE_SIZES and has_bool(f.type):
            raise SystemExit(
                f"ext_api.py: {struct_name}.{f.name} nests a bool inside "
                f"{f.type} — not supported on the wire, move the bool to the "
                f"top level of {struct_name}")


def struct_block(s):
    """Emit one typedef struct with its comments."""
    out = ""
    if s.doc is not None:
        if s.doc_style == "//":
            out += f"// {s.doc}\n"
        else:
            lines = s.doc.split("\n")
            if len(lines) == 1:
                out += f"/* {lines[0]} */\n"
            else:
                out += f"/* {lines[0]}\n"
                out += "\n".join(lines[1:]) + " */\n"
    out += "typedef struct\n{\n"
    for f in s.fields:
        if f.blank_before:
            out += "\n"
        if f.pre is not None:
            lines = f.pre.split("\n")
            if len(lines) == 1:
                out += f"    /* {lines[0]} */\n"
            else:
                out += f"    /* {lines[0]}\n"
                for line in lines[1:-1]:
                    out += f"    {line}\n"
                out += f"    {lines[-1]} */\n"
        out += f"    {f.type} {f.name};"
        if f.doc:
            out += f" // {f.doc}"
        out += "\n"
        if f.post is not None:
            out += f"    {f.post}\n"
    out += f"}} {s.name};\n"
    return out


def cfn_signature(cmd):
    if cmd.req is None:
        return f"{cfn_ret(cmd)} {cmd.cfn}(void)"
    if isinstance(cmd.req, tuple):
        _, t, n = cmd.req
        return f"{cfn_ret(cmd)} {cmd.cfn}({t} {n})"
    return f"{cfn_ret(cmd)} {cmd.cfn}({cmd.req} params)"


def cfn_ret(cmd):
    return cmd.resp


