def wire_req_name(cmd):
    return f"req{cmd.wire}_t"


def wire_resp_name(cmd):
    if cmd.resp == "bool":
        return "respBool_t"
    return f"resp{cmd.wire}_t"


def gen_ws_protocol():
    out = header("ws_protocol.hpp", [
        "Binary wire protocol shared between the WASM WebSocket proxy",
        "(client/ext_comm_ws.cpp) and the native core server",
        "(server/main.cpp + dispatch.cpp).",
        "One request -> one response. Packed little-endian structs;",
        "both peers are little-endian (WASM and x86/ARM).",
        "Request/response correlation is NOT part of this protocol:",
        "it is owned by the libs/ws transport, which frames every",
        "message with its own id before it reaches the wire.",
    ])
    out += "#pragma once\n#include <cstdint>\n#include \"ext_comm.hpp\"\n\n"
    out += "namespace ws_proto {\n\n"
    out += "constexpr uint16_t WS_DEFAULT_PORT = 9002;\n\n"

    # enum
    out += "/* Message types: request and matching response carry the same type id */\n"
    out += "enum MsgType : uint8_t\n{\n"
    ew = max(len(enum_name(c)) for c in COMMANDS)
    for cmd in COMMANDS:
        out += f"    {enum_name(cmd):<{ew}} = {cmd.id}, // -> {wire_resp_name(cmd)}\n"
    out += "};\n\n"

    out += "#pragma pack(push, 1)\n\n"
    out += "/* Common message header: every request/response starts with this */\n"
    out += "typedef struct\n{\n    uint8_t type; // MsgType, echoed in the response\n} header_t;\n\n"

    # validate wire-crossing structs before emitting anything
    for cmd in COMMANDS:
        if cmd.req is not None and not isinstance(cmd.req, tuple):
            _check_no_nested_bool(cmd.req)
        if cmd.resp != "bool":
            _check_no_nested_bool(cmd.resp)

    # requests: structs containing bool are expanded field by field with
    # bool -> uint8_t, exactly like the responses (symmetric conversion)
    out += "/* ------------------------------- requests ------------------------------- */\n"
    for cmd in COMMANDS:
        out += "\ntypedef struct\n{\n    header_t h;\n"
        if isinstance(cmd.req, tuple):
            _, t, n = cmd.req
            out += f"    {t} {n};\n"
        elif cmd.req is not None:
            if has_bool(cmd.req):
                for f in STRUCTS[cmd.req].fields:
                    t = "uint8_t" if f.type == "bool" else f.type
                    out += f"    {t} {f.name};\n"
            else:
                out += f"    {cmd.req} p;\n"
        out += f"}} {wire_req_name(cmd)};\n"

    # responses
    out += "\n/* ------------------------------ responses ------------------------------- */\n"
    out += "\n/* generic boolean response: isError follows the core convention (1 = error) */\n"
    out += "typedef struct\n{\n    header_t h;\n    uint8_t isError;\n} respBool_t;\n"
    for cmd in COMMANDS:
        if cmd.resp == "bool":
            continue
        out += "\ntypedef struct\n{\n    header_t h;\n"
        s = STRUCTS[cmd.resp]
        if has_bool(cmd.resp):
            for f in s.fields:
                t = "uint8_t" if f.type == "bool" else f.type
                out += f"    {t} {f.name};\n"
        else:
            out += f"    {cmd.resp} p;\n"
        out += f"}} {wire_resp_name(cmd)};\n"

    out += "\n#pragma pack(pop)\n\n"

    out += "/* Largest message either peer can send: used to size the shared RPC buffer */\n"
    out += "constexpr uint32_t WS_MAX_MSG_SIZE = 256;\n\n"

    # size asserts
    out += """\
/* Exact wire sizes, computed by the generator (f = sizeof(ext_coord_t) = 4):
   each peer checks them against its own ABI at compile time, so any layout
   drift (padding from mixed-size fields, architecture-dependent type widths)
   breaks the build instead of silently corrupting the parsing. */
"""
    rows = []
    for cmd in COMMANDS:
        rows.append((wire_req_name(cmd), req_size(cmd), req_breakdown(cmd)))
    seen_resp = set()
    for cmd in COMMANDS:
        name = wire_resp_name(cmd)
        if name in seen_resp:
            continue
        seen_resp.add(name)
        rows.append((name, resp_size(cmd), resp_breakdown(cmd)))
    nw = max(len(r[0]) for r in rows)
    out += f"static_assert(sizeof(header_t){' ' * (nw - len('header_t'))} ==  1, \"wire layout drift\");\n"
    for name, size, note in rows:
        out += (f"static_assert(sizeof({name}){' ' * (nw - len(name))} == "
                f"{size:>2}, \"wire layout drift\");{note}\n")
    for cmd in COMMANDS:
        assert req_size(cmd) < 256 and resp_size(cmd) < 256, "grow WS_MAX_MSG_SIZE"
    out += "\nstatic_assert(sizeof(reqTrajAppendPoly4_t) < WS_MAX_MSG_SIZE, \"wire msg too big\");\n"
    out += "static_assert(sizeof(respStep_t) < WS_MAX_MSG_SIZE, \"wire msg too big\");\n"
    out += "\n} // namespace ws_proto\n"
    return out


