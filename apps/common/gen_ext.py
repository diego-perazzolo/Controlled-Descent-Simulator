def gen_ext_defs():
    out = header("ext_defs.hpp", [
        "Struct definitions of the external communication API (the",
        "boundary shared by all apps and the embind bindings)",
    ])
    out += "\n#pragma once\n"
    blocks = []
    for item in DEFS:
        if isinstance(item, Raw):
            blocks.append(item.text)
        else:
            blocks.append(struct_block(item).rstrip("\n"))
    out += "\n\n".join(blocks) + "\n"
    return out


