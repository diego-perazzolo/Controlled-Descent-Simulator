def gen_ext_comm_hpp():
    out = header("ext_comm.hpp", [
        "External communication API (ext ↔ core adapter layer).",
        "Contract implemented by every adapter: ext_comm.cpp calls the",
        "core directly (wasm-only, ws-served server), ext_comm_ws.cpp",
        "forwards over WebSocket (ws-served client).",
    ])
    out += "#pragma once\n#include \"ext_defs.hpp\"\n\n/* structs */\n"
    for s in COMM:
        out += "\n" + struct_block(s)
    out += "\n"
    decls = []
    for cmd in COMMANDS:
        decls.append(f"/* {cmd.doc} */\n{cfn_signature(cmd)};\n")
    out += "\n".join(decls)
    return out


