CLIENT_PRELUDE = """\
#include <cstdint>
#include "ext_comm.hpp"
#include "ws_protocol.hpp"
#include "ws_rpc_client.hpp"

using namespace ws_proto;

/* Static functions */

/* Round-trips one request/response pair, returns true on error */
template <typename Req, typename Resp>
static bool _rpc(Req& req, Resp& resp)
{
    int n = ws_rpc(reinterpret_cast<const uint8_t*>(&req), sizeof(Req),
                   reinterpret_cast<uint8_t*>(&resp), sizeof(Resp));

    if(n != (int)sizeof(Resp))
    {
        // Err: transport failure or unexpected response size
        return true;
    }

    if(resp.h.type != req.h.type)
    {
        // Err: response does not match the request
        return true;
    }

    return false;
}

/* ext functions */
"""


def gen_client():
    out = header("ext_comm_ws.cpp", [
        "WebSocket adapter of the external communication API.",
        "Drop-in replacement for ext_comm.cpp: instead of calling the",
        "core directly, every ext_* call is marshalled into a",
        "ws_protocol message and round-tripped through the libs/ws",
        "synchronous RPC transport (ws_rpc_client) to a native server",
        "running the core. See ws_rpc_client.hpp for the transport",
        "requirements (COOP/COEP, bridge worker) and URL selection.",
    ])
    out += "\n" + CLIENT_PRELUDE

    for cmd in COMMANDS:
        rq, rs = wire_req_name(cmd), wire_resp_name(cmd)
        out += f"\n{cfn_signature(cmd)}\n{{\n"

        if cmd.resp == "bool":
            out += f"    {rq} req = {{}};\n    {rs} resp = {{}};\n\n"
            out += f"    req.h.type = {enum_name(cmd)};\n"
            out += _fill_req(cmd)
            out += "\n    if(_rpc(req, resp))\n    {\n        return true;\n    }\n\n"
            out += "    return resp.isError != 0;\n"
        elif has_bool(cmd.resp):
            s = STRUCTS[cmd.resp]
            out += f"    {cmd.resp} ret = {{}};\n"
            out += f"    {rq} req = {{}};\n    {rs} resp = {{}};\n\n"
            out += f"    req.h.type = {enum_name(cmd)};\n"
            out += _fill_req(cmd)
            bools = [f.name for f in s.fields if f.type == "bool"]
            out += "\n    if(_rpc(req, resp))\n    {\n"
            for b in bools:
                out += f"        ret.{b} = true;\n"
            out += "        return ret;\n    }\n\n"
            for f in s.fields:
                if f.type == "bool":
                    out += f"    ret.{f.name} = resp.{f.name} != 0;\n"
                else:
                    out += f"    ret.{f.name} = resp.{f.name};\n"
            out += "\n    return ret;\n"
        else:
            out += f"    {rq} req = {{}};\n    {rs} resp = {{}};\n\n"
            out += f"    req.h.type = {enum_name(cmd)};\n"
            out += _fill_req(cmd)
            out += "\n    if(_rpc(req, resp))\n    {\n        // Err\n        return {};\n    }\n\n"
            out += "    return resp.p;\n"
        out += "}\n"
    return out


def _fill_req(cmd):
    if cmd.req is None:
        return ""
    if isinstance(cmd.req, tuple):
        _, _, n = cmd.req
        return f"    req.{n} = {n};\n"
    if has_bool(cmd.req):
        out = ""
        for f in STRUCTS[cmd.req].fields:
            if f.type == "bool":
                out += f"    req.{f.name} = params.{f.name} ? 1 : 0;\n"
            else:
                out += f"    req.{f.name} = params.{f.name};\n"
        return out
    return "    req.p = params;\n"


