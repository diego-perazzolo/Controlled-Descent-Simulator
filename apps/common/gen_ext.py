TARGETS = {
    "apps/common/exported_cpp/ext_defs.hpp": gen_ext_defs,
    "apps/common/exported_cpp/ext_comm.hpp": gen_ext_comm_hpp,
    "apps/common/exported_cpp/bindings.cpp": gen_bindings,
    "apps/ws-served/exported_cpp/ws_protocol.hpp": gen_ws_protocol,
    "apps/ws-served/exported_cpp/ext_comm_ws.cpp": gen_client,
    "apps/ws-served/exported_cpp/dispatch.cpp": gen_dispatch,
}


def main():
    check = "--check" in sys.argv
    stale = []
    for rel, gen in TARGETS.items():
        path = os.path.join(ROOT, rel)
        content = gen()
        current = None
        if os.path.exists(path):
            with open(path) as fh:
                current = fh.read()
        if check:
            if current != content:
                stale.append(rel)
        elif current != content:
            # write only when the content changed, so untouched files keep
            # their mtime and the build trees do not recompile needlessly
            with open(path, "w") as fh:
                fh.write(content)
            print(f"generated {rel}")
        else:
            print(f"unchanged {rel}")
    if check:
        if stale:
            print("OUT OF SYNC with apps/common/ext_api.py:")
            for rel in stale:
                print(f"  {rel}")
            print("run: python3 apps/common/gen_ext.py")
            sys.exit(1)
        print("all generated files are in sync")


if __name__ == "__main__":
    main()
