def gen_bindings():
    out = header("bindings.cpp", [
        "Emscripten embind bindings: exposes the ext structs and the",
        "API functions to JavaScript. Identical for every browser app.",
    ])
    out += "\n#include <emscripten/bind.h>\n#include \"ext_comm.hpp\"\n\n"
    out += "using namespace emscripten;\n\n"
    out += "EMSCRIPTEN_BINDINGS(simulator) {\n\n"
    out += "    // --- Value types (struct) ---\n"

    structs = [s for s in DEFS + COMM if isinstance(s, Struct) and s.bind]
    blocks = []
    for s in structs:
        width = max(len(f.js) for f in s.fields) + 3  # name + quotes + comma
        b = f"    value_object<{s.name}>(\"{s.name}\")\n"
        rows = []
        for f in s.fields:
            js = f'"{f.js}",'
            rows.append(f"        .field({js:<{width}} &{s.name}::{f.name})")
        b += "\n".join(rows) + ";\n"
        blocks.append(b)
    out += "\n".join(blocks)

    out += "\n    // --- Functions exposed to JS ---\n"
    for cmd in COMMANDS:
        out += f"    function(\"{cmd.js}\", &{cmd.cfn});\n"
    out += "}\n"
    return out


